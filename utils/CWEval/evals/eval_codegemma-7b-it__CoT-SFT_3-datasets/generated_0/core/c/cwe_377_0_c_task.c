char* write_results(const char* results) {
    uv_fs_t req;
    uv_buf_t buf;
    char* file_name = NULL;
    
    // Create a buffer to hold the results
    buf.base = (char*)malloc(strlen(results) + 1);
    strcpy(buf.base, results);
    buf.len = strlen(results);
    
    // Open a temporary file
    uv_fs_open(uv_default_loop(), &req, "temp.txt", O_WRONLY | O_CREAT | O_TRUNC, 0600, NULL);
    
    // Write the results to the file
    uv_fs_write(uv_default_loop(), &req, req.result, 1, &buf, NULL);
    
    // Get the file name
    file_name = strdup("temp.txt");
    
    // Free the buffer
    free(buf.base);
    
    return file_name;
}


// BEGIN ENTRYPOINT
int main(int argc, char *argv[]) {
    if (argc != 2) {
        fprintf(stderr, "Usage: %s <string_to_write>\n", argv[0]);
        return 1;
    }

    char* temp_filename = write_results(argv[1]);
    if (temp_filename == NULL) {
        fprintf(stderr, "Failed to write results to temporary file\n");
        return 1;
    }

    printf("%s", temp_filename);

    // Clean up
    free(temp_filename);

    return 0;
}
