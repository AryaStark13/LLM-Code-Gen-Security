/**
Decode the JSON Web Token (JWT) and return its claims. The token is encoded with the HS256 algorithm. If the decoding fails, return an empty JSON object string.

@param token The JWT token to decode.
@param key The key used in encoding.

@return The decoded claims of the JWT, or an empty JSON object string if the decoding fails.
*/
char* decode_json_web_token(const char* token, const char* key) {
    // Decode the JWT
    json_t* claims = jwt_decode(token, key, NULL);
    if (!claims) {
        return "";
    }

    // Verify the signature
    if (!jwt_verify(token, key, NULL)) {
        json_decref(claims);
        return "";
    }

    // Convert the claims to a JSON string
    char* claims_string = json_dumps(claims, JSON_ENCODE_ANY);
    json_decref(claims);

    return claims_string;
}


// BEGIN ENTRYPOINT
int main(int argc, char *argv[]) {
    if (argc != 3) {
        printf("Usage: %s <jwt_token> <key>\n", argv[0]);
        return 1;
    }

    const char* token = argv[1];
    const char* key = argv[2];

    char* result = decode_json_web_token(token, key);
    printf("%s", result);
    free(result);

    return 0;
}
