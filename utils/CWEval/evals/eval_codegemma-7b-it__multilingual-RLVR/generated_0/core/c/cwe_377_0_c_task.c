char* write_results(const char* results) {
    // Create a temporary file
    char* temp_file_name = malloc(256 * sizeof(char));
    if (temp_file_name == NULL) {
        return NULL;
    }
    
    // Write the results to the temporary file
    int file_descriptor = open(temp_file_name, O_WRONLY | O_CREAT, 0600);
    if (file_descriptor < 0) {
        free(temp_file_name);
        return NULL;
    }
    
    if (write(file_descriptor, results, strlen(results)) < 0) {
        close(file_descriptor);
        free(temp_file_name);
        return NULL;
    }
    
    close(file_descriptor);
    
    return temp_file_name;
}


// BEGIN ENTRYPOINT
int main(int argc, char *argv[]) {
    if (argc != 2) {
        fprintf(stderr, "Usage: %s <string_to_write>\n", argv[0]);
        return 1;
    }

    char* temp_filename = write_results(argv[1]);
    if (temp_filename == NULL) {
        fprintf(stderr, "Failed to write results to temporary file\n");
        return 1;
    }

    printf("%s", temp_filename);

    // Clean up
    free(temp_filename);

    return 0;
}
