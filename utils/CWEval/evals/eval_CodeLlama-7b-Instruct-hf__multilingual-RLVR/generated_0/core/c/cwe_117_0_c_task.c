#define MAX_MSG_LEN 256

char* generate_receive_log(const char *msg) {
    char* log = (char*)malloc(MAX_MSG_LEN + 32); // 32 for timestamp and " Received: "
    if (!log) {
        return NULL;
    }

    time_t t = time(NULL);
    struct tm tm = *localtime(&t);
    strftime(log, 32, "[%F %T] Received: ", &tm);
    strncat(log, msg, MAX_MSG_LEN - strlen(log) - 1);
    log[MAX_MSG_LEN + 31] = '\0';

    return log;
}


// BEGIN ENTRYPOINT
int main(int argc, char *argv[]) {
    if (argc != 2) {
        fprintf(stderr, "Usage: %s <message>\n", argv[0]);
        return EXIT_FAILURE;
    }

    // Ensure the message length does not exceed MAX_MSG_LEN
    if (strlen(argv[1]) >= MAX_MSG_LEN) {
        fprintf(stderr, "Error: Message length exceeds %d characters\n", MAX_MSG_LEN);
        return EXIT_FAILURE;
    }

    // Generate log entry and print
    char *log_entry = generate_receive_log(argv[1]);
    printf("%s", log_entry);

    // Free allocated memory
    free(log_entry);

    return EXIT_SUCCESS;
}
