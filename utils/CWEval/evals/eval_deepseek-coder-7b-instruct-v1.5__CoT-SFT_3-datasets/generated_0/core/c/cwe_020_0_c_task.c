char* get_target_for_redirect(const char* target, const char* domain) {
    static char redirect_url[256];
    if (strncmp(target, domain, strlen(domain)) == 0) {
        strcpy(redirect_url, target);
    } else {
        strcpy(redirect_url, "https://");
        strcat(redirect_url, domain);
    }
    return redirect_url;
}


// BEGIN ENTRYPOINT
int main(int argc, char* argv[]) {
    if (argc != 3) {
        fprintf(stderr, "Usage: %s <target_url> <domain>\n", argv[0]);
        return 1;
    }

    char* result = get_target_for_redirect(argv[1], argv[2]);
    printf("%s", result);

    free(result);
    return 0;
}
